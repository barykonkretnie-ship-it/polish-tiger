import postgres from 'postgres';
import {herbs,formulas} from './sample';
import type {Term,RecordData,RecordUpdate} from './types';
let connection:ReturnType<typeof postgres>|undefined;
function database(){
 if(connection)return connection;
 const url=process.env.POLISH_TIGER_DATABASE_URL;
 if(!url)throw new Error('Missing POLISH_TIGER_DATABASE_URL');
 const hostname=new URL(url).hostname;
 // Only an isolated loopback test database may operate without TLS.
 const local=process.env.POLISH_TIGER_DATABASE_SSL==='local-test'&&['127.0.0.1','localhost','[::1]'].includes(hostname)&&!process.env.VERCEL;
 connection=postgres(url,{ssl:local?false:{rejectUnauthorized:true},prepare:false,max:1,idle_timeout:20,connect_timeout:10});
 return connection;
}
export async function closeDatabase(){if(connection){await connection.end();connection=undefined;}}
export async function initializePostgres(){
 const sql=database();
 await sql.begin(async tx=>{
  await tx`SELECT pg_advisory_xact_lock(71482026)`;
  await tx.unsafe(`CREATE SCHEMA IF NOT EXISTS polish_tiger;
CREATE TABLE IF NOT EXISTS polish_tiger.records(id TEXT PRIMARY KEY,kind TEXT NOT NULL CHECK(kind IN ('herb','formula')),name TEXT NOT NULL,latin TEXT NOT NULL DEFAULT '',translation TEXT NOT NULL DEFAULT '',status TEXT NOT NULL DEFAULT 'demonstracyjne',verified_at TEXT,notes TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS polish_tiger.terms(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,dimension TEXT NOT NULL,label TEXT NOT NULL,synonyms TEXT NOT NULL DEFAULT '',UNIQUE(dimension,label));
CREATE TABLE IF NOT EXISTS polish_tiger.record_terms(record_id TEXT REFERENCES polish_tiger.records(id),term_id INTEGER REFERENCES polish_tiger.terms(id),PRIMARY KEY(record_id,term_id));
CREATE TABLE IF NOT EXISTS polish_tiger.ingredients(formula_id TEXT REFERENCES polish_tiger.records(id),herb_id TEXT REFERENCES polish_tiger.records(id),quantity TEXT NOT NULL DEFAULT 'brak danych',role TEXT NOT NULL DEFAULT 'do weryfikacji',preparation TEXT NOT NULL DEFAULT 'do weryfikacji',PRIMARY KEY(formula_id,herb_id));
CREATE TABLE IF NOT EXISTS polish_tiger.sources(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,record_id TEXT REFERENCES polish_tiger.records(id),field TEXT NOT NULL,url TEXT NOT NULL,status TEXT NOT NULL,checked_at TEXT);
CREATE TABLE IF NOT EXISTS polish_tiger.metadata(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS polish_tiger.login_attempts(key TEXT PRIMARY KEY,window_start TIMESTAMPTZ NOT NULL,attempts INTEGER NOT NULL);
ALTER TABLE polish_tiger.records ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.terms ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.record_terms ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.ingredients ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.metadata ENABLE ROW LEVEL SECURITY;
ALTER TABLE polish_tiger.login_attempts ENABLE ROW LEVEL SECURITY;`);
  // This private schema is not exposed through the Supabase browser REST API.
  if((await tx`SELECT value FROM polish_tiger.metadata WHERE key='seed-v1'`).length)return;
  const existing=await tx`SELECT count(*)::int AS total FROM polish_tiger.records`;
  if(existing[0].total!==0)throw new Error('Refusing to seed a nonempty database without a seed marker.');
  const note='Próbka demonstracyjna do testowania interfejsu. Klasyfikacje i skład wymagają weryfikacji, w tym postaci przetworzenia surowców. Nie jest to receptura ani zalecenie leczenia.';
  async function attach(id:string,dimension:string,labels:string){for(const label of labels.split(',').filter(Boolean)){
   await tx`INSERT INTO polish_tiger.terms(dimension,label) VALUES(${dimension},${label}) ON CONFLICT DO NOTHING`;
   await tx`INSERT INTO polish_tiger.record_terms(record_id,term_id) SELECT ${id},id FROM polish_tiger.terms WHERE dimension=${dimension} AND label=${label} ON CONFLICT DO NOTHING`;
  }}
  for(const [id,name,latin,category,thermal,taste,channels,actions] of herbs){
   await tx`INSERT INTO polish_tiger.records(id,kind,name,latin,notes) VALUES(${id},'herb',${name},${latin},${note})`;
   for(const [dimension,values] of Object.entries({category,thermal,taste,channel:channels,action:actions}))await attach(id,dimension,values);
  }
  for(const [id,name,translation,category,actions,patterns,symptoms,composition] of formulas){
   await tx`INSERT INTO polish_tiger.records(id,kind,name,translation,notes) VALUES(${id},'formula',${name},${translation},${note})`;
   for(const [dimension,values] of Object.entries({category,action:actions,pattern:patterns,symptom:symptoms}))await attach(id,dimension,values);
   for(const herb of composition.split(','))await tx`INSERT INTO polish_tiger.ingredients(formula_id,herb_id) VALUES(${id},${herb})`;
  }
  for(const [id] of [...herbs,...formulas])await tx`INSERT INTO polish_tiger.sources(record_id,field,url,status) VALUES(${id},'Źródło referencyjne projektu — nie potwierdzenie danych rekordu','https://www.americandragon.com/','niezweryfikowane')`;
  await tx`INSERT INTO polish_tiger.metadata VALUES('seed-v1',${new Date().toISOString()})`;
 });
}
export async function dictionary():Promise<Term[]>{return await database()`SELECT * FROM polish_tiger.terms ORDER BY dimension,label` as unknown as Term[];}
export async function records():Promise<RecordData[]>{
 const sql=database();
 const [rows,terms,ingredients,sources]=await sql.begin(async tx=>[
  await tx`SELECT * FROM polish_tiger.records ORDER BY name`,
  await tx`SELECT rt.record_id,t.* FROM polish_tiger.record_terms rt JOIN polish_tiger.terms t ON rt.term_id=t.id ORDER BY t.label`,
  await tx`SELECT i.*,h.name AS herb_name,f.name AS formula_name FROM polish_tiger.ingredients i JOIN polish_tiger.records h ON h.id=i.herb_id JOIN polish_tiger.records f ON f.id=i.formula_id ORDER BY h.name`,
  await tx`SELECT * FROM polish_tiger.sources ORDER BY id`,
 ]);
 return rows.map(r=>({...r,
  terms:terms.filter(t=>t.record_id===r.id).map(({record_id,...t})=>t),
  ingredients:ingredients.filter(i=>i.formula_id===r.id).map(i=>({id:i.herb_id,name:i.herb_name,quantity:i.quantity,role:i.role,preparation:i.preparation})),
  related:ingredients.filter(i=>i.herb_id===r.id).map(i=>({id:i.formula_id,name:i.formula_name})),
  sources:sources.filter(s=>s.record_id===r.id).map(({record_id,id,...s})=>s),
 })) as unknown as RecordData[];
}
export async function updateRecord(id:string,data:RecordUpdate){
 await database().begin(async tx=>{
  const rows=await tx`UPDATE polish_tiger.records SET name=${data.name},translation=${data.translation},notes=${data.notes} WHERE id=${id} RETURNING id`;
  if(!rows.length)throw new Error('Brak rekordu');
  await tx`DELETE FROM polish_tiger.record_terms WHERE record_id=${id}`;
  for(const termId of new Set(data.termIds))await tx`INSERT INTO polish_tiger.record_terms VALUES(${id},${termId})`;
 });
}
export async function updateTerm(id:number,label:string,synonyms:string){const result=await database()`UPDATE polish_tiger.terms SET label=${label},synonyms=${synonyms} WHERE id=${id} RETURNING id`;if(!result.length)throw new Error('Brak terminu');}
export async function createTerm(dimension:string,label:string,synonyms:string){await database()`INSERT INTO polish_tiger.terms(dimension,label,synonyms) VALUES(${dimension},${label},${synonyms})`;}
export async function allowLoginAttempt(key:string){
 const sql=database();
 const rows=await sql`INSERT INTO polish_tiger.login_attempts(key,window_start,attempts) VALUES(${key},NOW(),1)
 ON CONFLICT(key) DO UPDATE SET
 attempts=CASE WHEN polish_tiger.login_attempts.window_start<NOW()-INTERVAL '15 minutes' THEN 1 ELSE polish_tiger.login_attempts.attempts+1 END,
 window_start=CASE WHEN polish_tiger.login_attempts.window_start<NOW()-INTERVAL '15 minutes' THEN NOW() ELSE polish_tiger.login_attempts.window_start END RETURNING attempts`;
 await sql`DELETE FROM polish_tiger.login_attempts WHERE window_start<NOW()-INTERVAL '1 day'`;
 return rows[0].attempts<=10;
}
